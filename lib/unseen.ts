/* ---------- leaderboard (localStorage) ---------- */
export interface ScoreEntry { name: string; score: number; total: number; date: string; game: string; }
const LB_KEY = 'unseen-boalkhali-leaderboard';
export function getLeaderboard(): ScoreEntry[] {
  if (typeof window === 'undefined') return [];
  try { return JSON.parse(localStorage.getItem(LB_KEY) || '[]'); } catch { return []; }
}
export function addScore(e: ScoreEntry) {
  if (typeof window === 'undefined') return;
  const all = [...getLeaderboard(), e].sort((a, b) => b.score - a.score || b.total - a.total).slice(0, 50);
  try { localStorage.setItem(LB_KEY, JSON.stringify(all)); } catch {}
}
