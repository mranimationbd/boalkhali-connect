/* ---------- project lon/lat to SVG viewBox (same math as the static site) ---------- */
const VB_W = 1000, VB_H = 760;
let _proj: { minLon: number; maxLon: number; minLat: number; maxLat: number } | null = null;
function bounds() {
  if (_proj) return _proj;
  let minLon = 99, maxLon = -99, minLat = 99, maxLat = -99;
  for (const ring of BOUNDARY) for (const [lo, la] of ring) {
    if (lo < minLon) minLon = lo; if (lo > maxLon) maxLon = lo;
    if (la < minLat) minLat = la; if (la > maxLat) maxLat = la;
  }
  const pad = 0.012;
  _proj = { minLon: minLon - pad, maxLon: maxLon + pad, minLat: minLat - pad, maxLat: maxLat + pad };
  return _proj;
}
export function project(lon: number, lat: number): [number, number] {
  const b = bounds();
  const x = ((lon - b.minLon) / (b.maxLon - b.minLon)) * VB_W;
  const y = VB_H - ((lat - b.minLat) / (b.maxLat - b.minLat)) * VB_H;
  return [x, y];
}
export function boundaryPath(): string {
  return BOUNDARY.map((ring) => ring.map(([lo, la], i) => {
    const [x, y] = project(lo, la);
    return (i === 0 ? 'M' : 'L') + x.toFixed(1) + ' ' + y.toFixed(1);
  }).join(' ') + ' Z').join(' ');
}
